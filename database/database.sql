
-- =====================================================
-- SISTEM INFORMASI AKUNTANSI
-- REKONSILIASI KAS DAN BANK PADA UMKM
-- Database: PostgreSQL / Supabase
-- =====================================================

-- Catatan:
-- Skrip ini untuk dokumentasi dan pembuatan database baru.
-- Jangan jalankan langsung pada database aktif yang sudah
-- memiliki tabel, karena tabel yang ada tidak perlu dibuat ulang.


-- =====================================================
-- 1. TABEL AKUN KAS DAN BANK
-- =====================================================

CREATE TABLE IF NOT EXISTS public.akun_kas_bank (
    id_akun BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_akun VARCHAR NOT NULL,
    jenis_akun VARCHAR NOT NULL,
    nomor_rekening VARCHAR,
    nama_bank VARCHAR,
    saldo_awal NUMERIC DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================
-- 2. TABEL TRANSAKSI KAS
-- =====================================================

CREATE TABLE IF NOT EXISTS public.transaksi_kas (
    id_transaksi BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_akun BIGINT NOT NULL,
    tanggal DATE NOT NULL,
    nomor_bukti VARCHAR,
    keterangan TEXT NOT NULL,
    jenis_transaksi VARCHAR NOT NULL,
    jumlah NUMERIC NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_transaksi_akun
        FOREIGN KEY (id_akun)
        REFERENCES public.akun_kas_bank (id_akun)
);


-- =====================================================
-- 3. TABEL MUTASI BANK
-- =====================================================

CREATE TABLE IF NOT EXISTS public.mutasi_bank (
    id_mutasi BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_akun BIGINT NOT NULL,
    tanggal DATE NOT NULL,
    referensi VARCHAR,
    keterangan TEXT NOT NULL,
    jenis_mutasi VARCHAR NOT NULL,
    jumlah NUMERIC NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_mutasi_akun
        FOREIGN KEY (id_akun)
        REFERENCES public.akun_kas_bank (id_akun)
);


-- =====================================================
-- 4. TABEL REKONSILIASI
-- =====================================================

CREATE TABLE IF NOT EXISTS public.rekonsiliasi (
    id_rekonsiliasi BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaksi BIGINT NOT NULL,
    id_mutasi BIGINT NOT NULL,
    tanggal_rekonsiliasi DATE DEFAULT CURRENT_DATE,
    status VARCHAR DEFAULT 'MATCHED',
    catatan TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_rekonsiliasi_transaksi
        FOREIGN KEY (id_transaksi)
        REFERENCES public.transaksi_kas (id_transaksi),

    CONSTRAINT fk_rekonsiliasi_mutasi
        FOREIGN KEY (id_mutasi)
        REFERENCES public.mutasi_bank (id_mutasi)
);


